import assert from 'node:assert/strict';
import { harness } from './verify-phase1.mjs';

const h=harness(), run=h.run;
assert.equal(run("data.guides.filter(g=>g.guide_id==='G-ZH-002').length"),1);
run("routeTo('#L01')");
assert.match(h.app.innerHTML,/Hong Kong &amp; Macao Travel Permit/);
run("routeTo('#L02?id=G-ZH-002')");
assert.match(h.app.innerHTML,/First permit/);
assert.match(h.app.innerHTML,/photo receipt/);
assert.match(h.app.innerHTML,/CNY 60/);
assert.match(h.app.innerHTML,/CNY 15/);
assert.match(h.app.innerHTML,/not guaranteed same-day/);
assert.match(h.app.innerHTML,/Gangle Road/);
assert.match(h.app.innerHTML,/Checked 2026-11-15/);
assert.equal(run('permitChoices().residence'),'unknown');
h.events.change({target:{id:'permit-residence',value:'other',dataset:{permitChoice:'residence'}}});
assert.match(h.app.innerHTML,/proof of enrolment/);
assert.match(h.app.innerHTML,/not this official proof/);
assert.ok(run("permitPreparation().some(t=>t.includes('proof of current enrolment'))"));
const itemText=run('permitPreparation()[0]');
h.events.change({target:{checked:true,dataset:{checklist:'G-ZH-002',checklistItem:itemText}}});
assert.equal(run(`state.checklist['G-ZH-002'].items[${JSON.stringify(itemText)}]`),true);
h.events.change({target:{id:'permit-service',value:'endorsement',dataset:{permitChoice:'service'}}});
assert.ok(run("permitPreparation().some(t=>t.includes('issued outside Guangdong'))"));
assert.equal(run("permitPreparation().some(t=>t.includes('Complete the Chinese Citizen'))"),false);
assert.equal(run(`state.checklist['G-ZH-002'].items[${JSON.stringify(itemText)}]`),true);
const reload=harness(h.storage);
assert.equal(reload.run('permitChoices().service'),'endorsement');
assert.equal(reload.run('permitChoices().residence'),'other');
assert.equal(reload.run(`state.checklist['G-ZH-002'].items[${JSON.stringify(itemText)}]`),true);
h.failWrites(true);
h.events.change({target:{id:'permit-residence',value:'guangdong',dataset:{permitChoice:'residence'}}});
assert.equal(run('permitChoices().residence'),'other');
h.failWrites(false);
h.events.change({target:{id:'permit-residence',value:'guangdong',dataset:{permitChoice:'residence'}}});
assert.equal(run('permitChoices().residence'),'guangdong');
assert.equal(run("permitPreparation().some(t=>t.includes('proof of current enrolment'))"),false);
run("state.profile=true; toggleSaved('guide','G-ZH-002'); routeTo('#M02?kind=guide')");
assert.match(h.app.innerHTML,/Hong Kong &amp; Macao/);
run("routeTo('#F01?kind=guide&id=G-ZH-002')");
assert.match(h.app.innerHTML,/Save Report on This Device/);
run("actions['reset-demo']()");
assert.equal(run('permitChoices().residence'),'unknown');
assert.equal(run('state.localActivities'),undefined);
assert.equal(run('state.communityThreads'),undefined);
console.log('PASS: permit guide discovery, first/endorsement branches, regional conditions, evidence links, fees, office, per-item checklist persistence, choice restore, failed-save rollback, saving/reporting and full local reset.');
