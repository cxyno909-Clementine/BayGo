import assert from 'node:assert/strict';
import { harness } from './verify-phase1.mjs';

const { run } = harness();
const result = expression => JSON.parse(run(`JSON.stringify(${expression})`));
assert.ok(run('Object.keys(window.BAYGO_PRICE_REFERENCES.records).length') >= 11);
assert.ok(run("Object.values(window.BAYGO_PRICE_REFERENCES.records).filter(r=>r.kind==='average_spend').length") >= 7);
const place = id => `directoryPlaces.find(p=>p.id===${JSON.stringify(id)})`;
assert.match(run(`placePriceDetails(${place('PL-ZH-002')})`), /CNY 33/);
assert.match(run(`placePriceDetails(${place('PL-ZH-002')})`), /Source checked/);
assert.equal(run(`priceReferenceRecord(${place('PL-ZH-003')})`), null);
assert.equal(run(`priceReferenceRecord(${place('PL-ZH-004')})`), null);
assert.match(run(`placePriceDetails(${place('PL-ZH-003')})`), /not been confirmed/);
assert.equal(run(`placePriceText(${place('PL-ZH-017')})`), 'Free general admission');
assert.match(run(`placePriceDetails(${place('PL-HK-008')})`), /HKD 190/);
assert.match(run(`placePriceDetails(${place('PL-HK-008')})`), /HKD 100/);
const subtotal = result("stopCostReferences(['PL-ZH-002','PL-ZH-002','PL-ZH-017','PL-HK-008','PL-ZH-003'])");
assert.deepEqual(subtotal.groups, { CNY: 33, HKD: 190 });
assert.equal(subtotal.total, 4);
assert.equal(subtotal.known, 3);
assert.deepEqual(subtotal.missing, ['PL-ZH-003']);
assert.match(run("stopCostPanel(['PL-ZH-003'])"), /not a complete trip budget/);
assert.match(run("stopCostPanel(['PL-ZH-003'])"), /No reliable stop-cost amounts/);
run("window.BAYGO_PRICE_REFERENCES.records['PL-ZH-002'].sourcePoiId='WRONG-BRANCH'");
assert.equal(run(`priceReferenceRecord(${place('PL-ZH-002')})`), null);
run("window.BAYGO_PRICE_REFERENCES.records['PL-HK-008'].currency='CNY'");
assert.equal(run(`priceReferenceRecord(${place('PL-HK-008')})`), null);
run("window.BAYGO_PRICE_REFERENCES.records['PL-ZH-017'].amount=-1");
assert.equal(run(`priceReferenceRecord(${place('PL-ZH-017')})`), null);
console.log('Price checks passed: source identity, historical dates, unknown/free distinction, concessions, partial subtotals and separate currencies.');
